def get_locale() -> str:
    if not has_request_context():
        return "en-US"
    saved_locale = session.get("locale")
    if saved_locale in SUPPORTED_LOCALES:
        return saved_locale
    country_code = request.headers.get("CF-IPCountry", "").strip().upper()
    return "zh-TW" if country_code in TRADITIONAL_CHINESE_COUNTRIES else "en-US"


def get_timezone_name() -> str:
    if not has_request_context():
        return "UTC"
    timezone_name = request.headers.get("CF-Timezone", "").strip()
    if not timezone_name or len(timezone_name) > 64:
        return "UTC"
    try:
        ZoneInfo(timezone_name)
    except (ValueError, ZoneInfoNotFoundError):
        return "UTC"
    return timezone_name


def _utc_datetime(value: datetime) -> datetime:
    if value.tzinfo is None:
        return value.replace(tzinfo=timezone.utc)
    return value.astimezone(timezone.utc)


def datetime_iso_utc(value: datetime | None) -> str:
    if value is None:
        return ""
    return _utc_datetime(value).isoformat().replace("+00:00", "Z")


def format_local_datetime(value: datetime | None, precision: str = "datetime") -> str:
    if value is None:
        return ""
    localized = _utc_datetime(value).astimezone(ZoneInfo(get_timezone_name()))
    return localized.strftime("%Y-%m-%d" if precision == "date" else "%Y-%m-%d %H:%M")


def translate(message: str) -> str:
    if get_locale() == "zh-TW":
        social_prefix = "Use full http(s) links for: "
        unsupported_suffix = " is not a supported image or video format."
        if message.startswith(social_prefix):
            return "請為以下項目使用完整的 http(s) 連結：" + message[len(social_prefix) :]
        if message.endswith(unsupported_suffix):
            return message[: -len(unsupported_suffix)] + " 不是支援的圖片或影片格式。"
        failed_prefix = "Email, username, or password is incorrect. "
        remaining_suffix = " attempts remaining."
        if message.startswith(failed_prefix) and message.endswith(remaining_suffix):
            count = message[len(failed_prefix) : -len(remaining_suffix)]
            return f"Email、使用者名稱或密碼不正確，還可嘗試 {count} 次。"
        locked_prefix = "Too many failed login attempts. Try again in "
        locked_suffix = " minutes."
        if message.startswith(locked_prefix) and message.endswith(locked_suffix):
            minutes = message[len(locked_prefix) : -len(locked_suffix)]
            return f"登入失敗次數過多，請在 {minutes} 分鐘後再試。"
        return ZH_TW.get(message, message)
    return message
